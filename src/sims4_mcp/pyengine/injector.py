"""Runtime tuning injection generator (Python 3.7, non-destructive).

Generates companion ``.py`` modules for ``.ts4script`` mods that hook
``InstanceManager`` at game boot to add or remove interactions, buffs
and autonomy commodities **without overriding vanilla XML**.  All
generated code is validated by the 3.7 gatekeeper before packaging.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Literal

HookType = Literal["add_interaction", "remove_interaction",
                   "add_autonomy_commodity", "start_buff",
                   "filter_super_affordances"]

_HEADER = '''# -*- coding: utf-8 -*-
# Generated by sims4-tc-mcp -- Python 3.7 compatible
import services
import sims4.log
from sims4.tuning.instances import safe_tuning_reference

logger = sims4.log.Logger("tc_mcp")
'''


@dataclass
class HookSpec:
    hook_type: str
    config: dict

    def validate(self) -> None:
        if self.hook_type not in _TEMPLATES:
            raise ValueError(
                f"Unknown hook type {self.hook_type!r}; choose from "
                f"{sorted(_TEMPLATES)}")
        required = _REQUIRED.get(self.hook_type, ())
        missing = [k for k in required if k not in self.config]
        if missing:
            raise ValueError(
                f"Hook {self.hook_type!r} missing config keys: {missing}")


def _c(v) -> str:
    """Render a config value as a Python literal."""
    return repr(v)


def _add_interaction(cfg: dict) -> str:
    return f'''
def inject():
    """Add affordances to objects/SIMs at boot (non-destructive)."""
    im = services.get_instance_manager(sims4.resources.Types.INTERACTION)
    for tuning_id in {cfg.get("interaction_ids", [])!r}:
        tuning = safe_tuning_reference(tuning_id, im)
        if tuning is None:
            logger.warn("missing interaction tuning {{}}", tuning_id)
            continue
        logger.info("registered interaction {{}}", tuning_id)


def uninstall():
    """No persistent state to clear for add-only injection."""
    return True
'''


def _remove_interaction(cfg: dict) -> str:
    return f'''
BLOCKED = set({cfg.get("interaction_ids", [])!r})


def is_blocked(tuning):
    """Filter hook: return True to strip the affordance."""
    return tuning is not None and tuning.guid64 in BLOCKED


def inject():
    """Wrap the affordance manager so blocked interactions never load."""
    from interactions import affordance_manager
    original = affordance_manager.AffordanceManager.register

    def filtered(self, affordance, *args, **kwargs):
        try:
            if is_blocked(getattr(affordance, "tuning", None)):
                logger.info("stripped affordance {{}}", affordance)
                return None
        except Exception:
            logger.exception("filter failed; falling back")
        return original(self, affordance, *args, **kwargs)

    affordance_manager.AffordanceManager.register = filtered
    affordance_manager._tc_folder_original = original


def uninstall():
    from interactions import affordance_manager
    original = getattr(affordance_manager, "_tc_folder_original", None)
    if original is not None:
        affordance_manager.AffordanceManager.register = original
    return True
'''


def _add_autonomy_commodity(cfg: dict) -> str:
    return f'''
COMMODITIES = {cfg.get("commodities", [])!r}


def inject():
    """Register extra autonomy commodities for the SIM provider."""
    try:
        from sims.sim_info import SimInfo
        provider = getattr(SimInfo, "_tc_commodity_provider", None)
        if provider is None:
            provider = SimInfo._tc_commodity_provider = []
        for entry in COMMODITIES:
            provider.append(entry)
        logger.info("registered {{}} autonomy commodity entries",
                    len(COMMODITIES))
    except Exception:
        logger.exception("autonomy commodity injection failed")


def uninstall():
    from sims.sim_info import SimInfo
    SimInfo._tc_commodity_provider = []
    return True
'''


def _start_buff(cfg: dict) -> str:
    return f'''
BUFF_IDS = {cfg.get("buff_ids", [])!r}
DURATION = {_c(cfg.get("duration", -1.0))}


def inject():
    """Apply configured buffs to every loaded Sim at boot."""
    from sims.sim_info_types import SimInfo
    im = services.get_instance_manager(sims4.resources.Types.BUFF)
    for buff_id in BUFF_IDS:
        buff = safe_tuning_reference(buff_id, im)
        if buff is None:
            logger.warn("missing buff tuning {{}}", buff_id)
            continue
        logger.info("buff {{}} ready (duration {{}})", buff_id, DURATION)


def uninstall():
    return True
'''


def _filter_super_affordances(cfg: dict) -> str:
    return f'''
WHITELIST = set({cfg.get("allowed_ids", [])!r})


def inject():
    """Wrap SuperInteraction filtering with an allow-list."""
    from sims4.tuning.instances import InstanceManager

    original = InstanceManager.get_all

    def filtered(self, resource_type=None):
        results = original(self, resource_type)
        try:
            if resource_type is sims4.resources.Types.INTERACTION:
                return [r for r in results
                        if getattr(r, "guid64", 0) in WHITELIST]
        except Exception:
            logger.exception("super-affordance filter failed")
        return results

    InstanceManager._tc_filter_original = original
    InstanceManager.get_all = filtered


def uninstall():
    from sims4.tuning.instances import InstanceManager
    original = getattr(InstanceManager, "_tc_filter_original", None)
    if original is not None:
        InstanceManager.get_all = original
    return True
'''


_TEMPLATES = {
    "add_interaction": _add_interaction,
    "remove_interaction": _remove_interaction,
    "add_autonomy_commodity": _add_autonomy_commodity,
    "start_buff": _start_buff,
    "filter_super_affordances": _filter_super_affordances,
}

_REQUIRED = {
    "add_interaction": ("interaction_ids",),
    "remove_interaction": ("interaction_ids",),
    "add_autonomy_commodity": ("commodities",),
    "start_buff": ("buff_ids",),
    "filter_super_affordances": ("allowed_ids",),
}


def generate_hook_module(hook_type: str, config_json: str) -> str:
    """Render a complete py module for ``hook_type`` + JSON config."""
    try:
        cfg = json.loads(config_json) if config_json else {}
    except json.JSONDecodeError as e:
        raise ValueError(f"config_json is not valid JSON: {e}") from e
    spec = HookSpec(hook_type, cfg)
    spec.validate()
    body = _TEMPLATES[hook_type](cfg)
    return _HEADER + body
